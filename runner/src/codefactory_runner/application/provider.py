from typing import Protocol
from codefactory_runner.contracts.runner_request import RunnerRequest
from codefactory_runner.contracts.runner_result import RunnerResult


class ExecutionProvider(Protocol):
    """Only the independent runner may implement physical CLI execution later."""

    async def execute_task(self, request: RunnerRequest) -> RunnerResult: ...
    async def cancel_task(self, attempt_id: str) -> RunnerResult: ...
    async def get_status(self, attempt_id: str) -> RunnerResult: ...
    async def get_result(self, attempt_id: str) -> RunnerResult: ...
    async def detect_authentication(self) -> str: ...
    async def detect_quota_limit(self) -> str: ...
    async def detect_availability(self) -> str: ...
